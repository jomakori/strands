import { chromium } from '@playwright/test';
const b = await chromium.launch();
const page = await b.newPage({ viewport: { width: 360, height: 800 } });
const hits = [];
let approved = null;
const versions = [{id:"11111111-1111-4111-8111-111111111111",tag_id:"9b83f584-7f85-5848-a1cb-3bea4729b1e5",version:1,body:"Proposed text.",guide:{kind:"shorter"},model_alias:"m",state:"proposed",created_at:"2026-03-10T09:00:00Z"}];
await page.route("**/api/v1/tags/*/summary/history", async r => r.fulfill({json:{versions, approved_version_id: approved}}));
await page.route("**/api/v1/tags/*/summary/*/approve", async r => { hits.push("approve"); versions[0].state="approved"; approved=versions[0].id; await r.fulfill({json:{versions, approved_version_id: approved}}); });
await page.route("**/api/v1/tags/*/summary/*/discard", async r => { hits.push("discard"); await r.fulfill({json:{versions, approved_version_id: approved}}); });
page.on('console', m => console.log('CONSOLE:', m.type(), m.text()));
page.on('request', r => { if (r.url().includes('/api/')) console.log('REQ', r.method(), r.url()); });
page.on('response', r => { if (r.url().includes('/api/')) console.log('RES', r.status(), r.url()); });
await page.goto("http://127.0.0.1:4173/");
await page.locator("#grid [data-tag-id]").first().click();
await page.waitForTimeout(1500);
console.log("card:", (await page.locator("#summary-card").innerText()).slice(0,400));
console.log('active element:', await page.evaluate(() => document.activeElement && document.activeElement.tagName + '#' + document.activeElement.id));
await page.keyboard.press("h");
await page.waitForTimeout(300);
console.log('hits after h:', hits, 'versions visible:', await page.locator("#summary-versions").isVisible());
await page.keyboard.press("a");
await page.waitForTimeout(500);
console.log('hits after a:', hits, 'body:', await page.locator("#summary-body").textContent());
await page.evaluate(() => document.dispatchEvent(new KeyboardEvent('keydown', {key:'a', bubbles:true})));
await page.waitForTimeout(500);
console.log('hits after synthetic:', hits, 'body:', await page.locator("#summary-body").textContent());
await b.close();
